const BY_KEY = new Map(CATEGORY_ICON_THEMES.flatMap((theme) => theme.icons.map((icon) => [icon.key, icon] as const)));

/** The icon for a stored key; null for null or a key this build doesn't know (a newer API's): the tile shows its letter. */
export function findCategoryIcon(key: string | null): CategoryIcon | null {
  return key === null ? null : (BY_KEY.get(key) ?? null);
}
